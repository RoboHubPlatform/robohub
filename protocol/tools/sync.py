"""Keep every copy of the RoboHub wire protocol the source's.

    tools/sync.py            write the copies and regenerate each consumer
    tools/sync.py --check    change nothing; exit 1 and say what differs

The consumers are listed in consumers.yml. The workspace they are found in is
ROBOHUB_WORKSPACE, or the directory the robohub checkout is in. A consumer that
is not checked out is said and passed over: a machine need not hold every
repository.

The check regenerates into a temporary directory and compares, so it finds a
generated file edited by hand, or generated by an older toolchain, as well as a
schema copy that is out of step.
"""

import filecmp
import os
import shutil
import subprocess
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMAS = os.path.join(HERE, "schemas")


def workspace():
    env = os.environ.get("ROBOHUB_WORKSPACE", "")
    if env:
        return env
    return os.path.dirname(os.path.dirname(HERE))


def generate(entry, schemas_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    cmd = ["rho", "protocol", "generate", "--target", entry["target"], "--platform", "robohub",
           "--out", out_dir, os.path.join(schemas_dir, entry["schema"])]
    done = subprocess.run(cmd, capture_output=True, text=True)
    if done.returncode != 0:
        raise RuntimeError(" ".join(cmd) + "\n" + done.stderr.strip())


def differs(a, b):
    return not (os.path.exists(b) and filecmp.cmp(a, b, shallow=False))


def main(argv):
    check = "--check" in argv
    root = workspace()
    with open(os.path.join(HERE, "consumers.yml")) as f:
        consumers = yaml.safe_load(f)["consumers"]
    drift = []
    for consumer in consumers:
        base = os.path.join(root, consumer["path"])
        if not os.path.isdir(base):
            print(f"  skip  {consumer['path']}: not checked out")
            continue
        schemas_dir = os.path.join(base, "schemas")
        for name in consumer["schemas"]:
            source = os.path.join(SCHEMAS, name + ".rho")
            copy = os.path.join(schemas_dir, name + ".rho")
            if differs(source, copy):
                drift.append(f"{consumer['path']}/schemas/{name}.rho")
                if not check:
                    os.makedirs(schemas_dir, exist_ok=True)
                    shutil.copyfile(source, copy)
        for entry in consumer.get("generate", []):
            out = os.path.join(base, entry["out"])
            with tempfile.TemporaryDirectory() as scratch:
                # Generated from the source, so a check sees what a sync would write.
                generate(entry, SCHEMAS, scratch)
                for produced in sorted(os.listdir(scratch)):
                    target = os.path.join(out, produced)
                    if differs(os.path.join(scratch, produced), target):
                        drift.append(f"{consumer['path']}/{entry['out']}/{produced}")
                        if not check:
                            os.makedirs(out, exist_ok=True)
                            shutil.copyfile(os.path.join(scratch, produced), target)
    verb = "differs" if check else "written"
    for path in drift:
        print(f"  {verb}  {path}")
    if not drift:
        print("every consumer is the source's")
    return 1 if (check and drift) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
